#!/usr/bin/env python3
"""From the normal set of a face of a hive polytope to its transverse cone and its weight.

For a face F of a polytope P = {x : <n_i, x> <= b_i} the normal cone is generated by the outward
normals of the facets through F; write S for that set and W for its span. The transverse cone is
the image of the tangent cone of P along F in the quotient by lin(F), which Berline and Vergne
identify with the orthogonal complement of lin(F), that is with W, carrying the projected lattice:

    T = { y in W : <n, y> <= 0 for every n in S },     Lambda_W = projection of Z^d on W.

`transverse_cone` returns T in coordinates of a basis of Lambda_W, together with the Gram matrix
of that basis, which is what `bvweight.weight` consumes. Non-simplicial transverse cones are
triangulated without new rays and summed with the inclusion-exclusion of the valuation property.
"""
from __future__ import annotations

import os
import sys
from fractions import Fraction
from typing import List, Sequence, Tuple

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bvweight import _Proj, _gcd, lattice_basis, rank, weight, _rref  # noqa: E402


def transverse_cone(normals: Sequence[Sequence[int]], d: int = 6):
    """(rays of T in lattice coordinates, Gram matrix of the lattice basis)."""
    from PyNormaliz import Cone  # type: ignore

    G = [[Fraction(1 if i == j else 0) for j in range(d)] for i in range(d)]
    span = [list(map(int, n)) for n in normals]
    r = rank(span)
    # a basis of the projection of Z^d on W = span(normals): project off the orthogonal complement
    comp = _orthogonal_complement(span, d)
    pr = _Proj(comp, G)
    gens = [pr([1 if c == i else 0 for c in range(d)]) for i in range(d)]
    den = 1
    for g in gens:
        for x in g:
            den = den * x.denominator // _gcd(den, x.denominator)
    base = [[Fraction(x, den) for x in b]
            for b in lattice_basis([[int(x * den) for x in g] for g in gens])]
    assert len(base) == r, f"projected lattice has rank {len(base)}, expected {r}"
    # T in these coordinates: sum_a c_a <n, b_a> <= 0, that is -sum_a c_a <n, b_a> >= 0
    ineq = []
    for n in span:
        row = [-sum(Fraction(n[i]) * base[a][i] for i in range(d)) for a in range(r)]
        m = 1
        for x in row:
            m = m * x.denominator // _gcd(m, x.denominator)
        ineq.append([int(x * m) for x in row])
    C = Cone(inequalities=ineq)
    rays = [tuple(int(x) for x in v) for v in C.ExtremeRays()]
    gram = [[sum(base[a][i] * base[b][i] for i in range(d)) for b in range(r)] for a in range(r)]
    return rays, gram


def _orthogonal_complement(span: Sequence[Sequence[int]], d: int) -> List[List[int]]:
    """An integer basis of the orthogonal complement of the span, for the standard product."""
    from bvweight import int_kernel
    return int_kernel(span, d)


def transverse_weight(normals: Sequence[Sequence[int]], d: int = 6) -> Fraction:
    """The local weight of the transverse cone of a face with the given outward normals."""
    rays, gram = transverse_cone(normals, d)
    r = len(gram)
    if len(rays) == r:
        return weight(rays, gram)
    return _triangulated_weight(rays, gram)


def _triangulated_weight(rays: Sequence[Sequence[int]], gram) -> Fraction:
    """Weight of a non-simplicial cone, by a triangulation and the valuation property.

    Normaliz returns a triangulation into simplicial cones using no new rays, as a pair of the
    simplex list and the generator list it indexes. The pieces meet in lower-dimensional cones,
    so the weight of the union is the inclusion-exclusion of the weights of the intersections of
    the pieces, which are the cones on the common generator sets.
    """
    from PyNormaliz import Cone  # type: ignore
    from itertools import combinations

    C = Cone(cone=[list(v) for v in rays])
    tri = C.Triangulation()
    simplices = [tuple(sorted(s[0])) for s in tri[0]]
    gens = [tuple(int(x) for x in g) for g in tri[1]]
    total = Fraction(0)
    cache = {}
    n = len(simplices)
    for size in range(1, n + 1):
        sign = (-1) ** (size + 1)
        for sub in combinations(range(n), size):
            common = set(simplices[sub[0]])
            for s in sub[1:]:
                common &= set(simplices[s])
            key = tuple(sorted(common))
            if not key:
                continue
            if key not in cache:
                sel = [list(gens[i]) for i in key]
                cache[key] = weight(sel, gram) if rank(sel) == len(sel) else None
            if cache[key] is not None:
                total += sign * cache[key]
    return total
