#!/usr/bin/env python3
"""Gate one for a candidate scalar product: the vertex-sum identity.

Amendment 3 of the independent review of 2026-09-05. For any lattice polytope the local
Euler-Maclaurin formula read at codimension equal to the dimension says that the weights of the
tangent cones at the vertices sum to the constant Ehrhart coefficient, which is 1. The test is
exact, needs no Ehrhart computation, and is necessary for a candidate form to give a valid local
formula. It is not sufficient.

Polytopes used: the unit cube in dimension six, whose 64 tangent cones are the signed orthants,
and a lattice simplex whose 7 tangent cones are generated by the differences of its vertices.
"""
from __future__ import annotations

import itertools
import json
import os
import sys
import time
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from bvweight import weight  # noqa: E402

D = 6


def form(name):
    if name == "standard":
        return [[Fraction(1 if i == j else 0) for j in range(D)] for i in range(D)]
    if name == "A_6":
        return [[Fraction(2 if i == j else (-1 if abs(i - j) == 1 else 0)) for j in range(D)]
                for i in range(D)]
    if name == "twice the standard":
        return [[Fraction(2 if i == j else 0) for j in range(D)] for i in range(D)]
    if name.startswith("I plus "):
        t = Fraction(name[len("I plus "):])
        return [[Fraction(1) if i == j else t for j in range(D)] for i in range(D)]
    raise KeyError(name)


def cube_vertex_sum(G, budget, t0):
    total = Fraction(0)
    done = 0
    for signs in itertools.product((1, -1), repeat=D):
        rays = [[signs[i] if i == j else 0 for j in range(D)] for i in range(D)]
        total += weight(rays, G)
        done += 1
        if time.time() - t0 > budget:
            return None, done
    return total, done


def simplex_vertex_sum(G, verts):
    total = Fraction(0)
    for i, v in enumerate(verts):
        rays = [[verts[j][k] - v[k] for k in range(D)] for j in range(len(verts)) if j != i]
        total += weight(rays, G)
    return total


def main():
    budget = float(os.environ.get("BUDGET", "1500"))
    t0 = time.time()
    simplex = [[0] * D] + [[1 if i == j else 0 for j in range(D)] for i in range(D)]
    out = []
    for name in ("standard", "twice the standard", "A_6", "I plus 1/4"):
        if time.time() - t0 > budget:
            break
        G = form(name)
        s, n = simplex_vertex_sum(G, simplex), 7
        rec = {"form": name, "unimodular simplex: vertices": n,
               "unimodular simplex: sum of the vertex weights": str(s),
               "unimodular simplex: identity holds": s == 1}
        print(json.dumps(rec), flush=True)
        c, done = cube_vertex_sum(G, budget, t0)
        rec["cube: vertices evaluated"] = done
        rec["cube: sum of the vertex weights"] = str(c) if c is not None else None
        rec["cube: identity holds"] = (c == 1) if c is not None else None
        rec["seconds so far"] = round(time.time() - t0)
        out.append(rec)
        print(json.dumps(rec), flush=True)
    json.dump({"gate": "the vertex-sum identity, necessary and not sufficient",
               "forms": out, "seconds": round(time.time() - t0)},
              open(os.path.join(HERE, "gate.json"), "w"), indent=2)


if __name__ == "__main__":
    main()
