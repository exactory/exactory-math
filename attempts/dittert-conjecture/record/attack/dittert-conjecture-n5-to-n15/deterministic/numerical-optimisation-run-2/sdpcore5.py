"""Shared machinery for the n = 5 symmetry-reduced SOS certificate (route B).

Same constructions as sdp5.py (monomial indices, the G_5 action, pair orbits by label
propagation, numerical block diagonalisation by two generic invariant matrices, the
W matrices from block variables to orbit coordinates), packaged as functions, plus
the integer count matrices that express the coefficient equations and the
vanishing-at-U_5 equations directly in orbit coordinates, which the exact recovery
needs.  Importable; nothing runs on import.
"""
import itertools
import pickle
import time

import numpy as np

n = 5
N = n * n
T0 = time.time()


def log(msg):
    print(f"[{time.time() - T0:7.1f}s] {msg}", flush=True)


class MonoIndex:
    def __init__(self, d):
        self.d = d
        self.mons = np.array(list(itertools.combinations_with_replacement(range(N), d)), dtype=np.int64)
        self.w = N ** np.arange(d, dtype=np.int64)
        self.keys = (self.mons * self.w).sum(1)
        self.order = np.argsort(self.keys)
        self.sk = self.keys[self.order]

    def index(self, arr):
        arr = np.asarray(arr, dtype=np.int64)
        k = (np.sort(arr, axis=-1) * self.w).sum(-1)
        pos = np.searchsorted(self.sk, k)
        assert np.all(self.sk[pos] == k)
        return self.order[pos]


def var(i, j):
    return i * n + j


def varperm(rowp=None, colp=None, transpose=False):
    rowp = rowp or list(range(n))
    colp = colp or list(range(n))
    g = np.zeros(N, dtype=np.int64)
    for i in range(n):
        for j in range(n):
            a, b = (j, i) if transpose else (i, j)
            g[var(i, j)] = var(rowp[a], colp[b])
    return g


IDENT = list(range(n))
GENS = [varperm([1, 0, 2, 3, 4]), varperm([1, 2, 3, 4, 0]), varperm(colp=[1, 0, 2, 3, 4]),
        varperm(colp=[1, 2, 3, 4, 0]), varperm(transpose=True)]
PAIR_REPS = {"aligned": (0, 1), "generic": (0, 6)}
STAB_GENS = {
    "aligned": [varperm(rowp=[0, 2, 1, 3, 4]), varperm(rowp=[0, 2, 3, 4, 1]),
                varperm(colp=[0, 1, 3, 2, 4]), varperm(colp=[0, 1, 3, 4, 2]), varperm(colp=[1, 0, 2, 3, 4])],
    "generic": [varperm(rowp=[0, 1, 3, 2, 4]), varperm(rowp=[0, 1, 3, 4, 2]),
                varperm(colp=[0, 1, 3, 2, 4]), varperm(colp=[0, 1, 3, 4, 2]),
                varperm(rowp=[1, 0, 2, 3, 4], colp=[1, 0, 2, 3, 4]), varperm(transpose=True)],
}


def orbits(V, gs):
    """Orbit label (smallest index in the orbit) of every monomial of V under the group generated by gs."""
    M = len(V.mons)
    perms = [V.index(g[V.mons]) for g in gs]
    perms += [np.argsort(p) for p in perms]
    lab = np.arange(M, dtype=np.int64)
    while True:
        old = lab.copy()
        for p in perms:
            lab = np.minimum(lab, lab[p])
        if np.array_equal(old, lab):
            return lab


def pair_orbits(V, gs):
    M = len(V.mons)
    perms = [V.index(g[V.mons]) for g in gs]
    perms += [np.argsort(p) for p in perms]
    lab = np.arange(M * M, dtype=np.int64)
    a, b = lab // M, lab % M
    while True:
        old = lab.copy()
        for p in perms:
            lab = np.minimum(lab, lab[p[a] * M + p[b]])
        if np.array_equal(old, lab):
            return lab


def block_diagonalise(lab, M, rng, tol=1e-6):
    u, inv = np.unique(lab, return_inverse=True)
    K = len(u)

    def rand_inv():
        R = rng.standard_normal(K)[inv].reshape(M, M)
        return (R + R.T) / 2

    R1, R2, R3 = rand_inv(), rand_inv(), rand_inv()
    w, V = np.linalg.eigh(R1)
    scale = np.abs(w).max()
    clusters, start = [], 0
    for i in range(1, M + 1):
        if i == M or w[i] - w[i - 1] > tol * scale:
            clusters.append(list(range(start, i)))
            start = i
    Y = np.einsum("ji,jk->ik", V, R2, optimize=True)
    Y = np.einsum("ij,jk->ik", Y, V, optimize=True)
    yscale = np.abs(Y).max()
    parent = list(range(len(clusters)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for i in range(len(clusters)):
        for j in range(i + 1, len(clusters)):
            if len(clusters[i]) == len(clusters[j]) and np.abs(Y[np.ix_(clusters[i], clusters[j])]).max() > tol * yscale:
                parent[find(i)] = find(j)
    groups = {}
    for i in range(len(clusters)):
        groups.setdefault(find(i), []).append(i)
    Bmat = np.zeros((M, M))
    blocks, col = [], 0
    for g in groups.values():
        cl = [clusters[i] for i in g]
        d = len(cl[0])
        assert all(len(c) == d for c in cl)
        m = len(cl)
        cols = [V[:, cl[0]]]
        for c in cl[1:]:
            Bk = np.einsum("ij,jk->ik", V[:, c], Y[np.ix_(c, cl[0])])
            Bk = Bk / np.linalg.norm(Bk[:, 0])
            assert np.allclose(np.einsum("ji,jk->ik", Bk, Bk), np.eye(d), atol=1e-6)
            cols.append(Bk)
        for k, Bk in enumerate(cols):
            Bmat[:, col + k * d: col + (k + 1) * d] = Bk
        blocks.append((m, d, col))
        col += m * d
    assert col == M
    Z = np.einsum("ji,jk->ik", Bmat, R3, optimize=True)
    Z = np.einsum("ij,jk->ik", Z, Bmat, optimize=True)
    err = 0.0
    for (m, d, s) in blocks:
        Tm = Z[s:s + m * d, s:s + m * d].reshape(m, d, m, d)
        X = Tm[:, 0, :, 0]
        for al in range(d):
            for be in range(d):
                err = max(err, np.abs(Tm[:, al, :, be] - (X if al == be else 0)).max())
    off = Z.copy()
    for (m, d, s) in blocks:
        off[s:s + m * d, s:s + m * d] = 0
    err = max(err, np.abs(off).max())
    assert err < 1e-6 * np.abs(Z).max(), f"block verification failed: {err}"
    return Bmat, blocks


def W_matrix(lab, M, Bmat, blocks):
    u = np.unique(lab)
    a, b = u // M, u % M
    parts = []
    for (m, d, s) in blocks:
        Ba = Bmat[a][:, s:s + m * d].reshape(len(u), m, d)
        Bb = Bmat[b][:, s:s + m * d].reshape(len(u), m, d)
        parts.append(np.einsum("kmd,knd->kmn", Ba, Bb).reshape(len(u), m * m))
    return np.concatenate(parts, axis=1), {int(o): i for i, o in enumerate(u)}


def transports():
    """For every unordered pair of distinct entries, its orbit type and a variable permutation g with g(rep) = pair."""
    tr = {}
    for typ, rep in PAIR_REPS.items():
        e = np.arange(N)
        tr[frozenset(rep)] = (typ, e)
        frontier = [(frozenset(rep), e)]
        while frontier:
            nxt = []
            for pr, perm in frontier:
                for g in GENS:
                    img = frozenset(int(g[x]) for x in pr)
                    if img not in tr:
                        tr[img] = (typ, g[perm])
                        nxt.append((img, g[perm]))
            frontier = nxt
    assert len(tr) == 300
    return tr


def build(seed=20260903):
    """Everything the SDP and the exact recovery need."""
    data = pickle.load(open("poly5.pkl", "rb"))
    V3, V2 = MonoIndex(3), MonoIndex(2)
    assert np.array_equal(MonoIndex(6).mons, data["mons"])
    M3, M2 = len(V3.mons), len(V2.mons)
    rng = np.random.default_rng(seed)
    S = dict(V3=V3, V2=V2, mons6=data["mons"], labels6=data["labels"], reps6=data["reps"],
             Qrep=data["Q_at_rep"], Drep=data["D_at_rep"], transport=transports())
    log("main: pair orbits and block diagonalisation")
    S["lab3"] = pair_orbits(V3, GENS)
    S["Bmat3"], S["blocks3"] = block_diagonalise(S["lab3"], M3, rng)
    S["W3"], S["orb3"] = W_matrix(S["lab3"], M3, S["Bmat3"], S["blocks3"])
    S["mono_orb3"] = orbits(V3, GENS)
    S["mult"] = {}
    for typ in PAIR_REPS:
        lab2 = pair_orbits(V2, STAB_GENS[typ])
        B2, bl2 = block_diagonalise(lab2, M2, rng)
        W2, orb2 = W_matrix(lab2, M2, B2, bl2)
        S["mult"][typ] = dict(lab=lab2, B=B2, blocks=bl2, W=W2, orb=orb2, mono_orb=orbits(V2, STAB_GENS[typ]))
    log("count matrices in orbit coordinates")
    reps6 = S["reps6"]
    R = len(reps6)
    cnt = {"main": np.zeros((R, len(S["orb3"])), dtype=np.int64),
           **{typ: np.zeros((R, len(S["mult"][typ]["orb"])), dtype=np.int64) for typ in PAIR_REPS}}
    for ri, r in enumerate(reps6):
        mu = tuple(int(x) for x in S["mons6"][r])
        seen = set()
        for Ss in itertools.combinations(range(6), 3):
            seen.add((tuple(mu[i] for i in Ss), tuple(mu[i] for i in range(6) if i not in Ss)))
        for a, b in seen:
            ia, ib = int(V3.index(a)), int(V3.index(b))
            cnt["main"][ri, S["orb3"][int(S["lab3"][ia * M3 + ib])]] += 1
        for u, v in itertools.combinations(sorted(set(mu)), 2):
            rest = list(mu)
            rest.remove(u)
            rest.remove(v)
            typ, perm = S["transport"][frozenset((u, v))]
            ginv = np.argsort(perm)
            seen = set()
            for Ss in itertools.combinations(range(4), 2):
                seen.add((tuple(rest[i] for i in Ss), tuple(rest[i] for i in range(4) if i not in Ss)))
            mt = S["mult"][typ]
            for a, b in seen:
                ia, ib = int(V2.index(ginv[list(a)])), int(V2.index(ginv[list(b)]))
                cnt[typ][ri, mt["orb"][int(mt["lab"][ia * M2 + ib])]] += 1
    S["cnt"] = cnt
    # vanishing at U_5: M 1 = 0, one equation per monomial orbit (row a fixed): sum_b M[a,b] = sum_O m_O #{b : (a,b) in O}
    def rowsum_matrix(lab, mono_orb, orb, M):
        reps = np.unique(mono_orb)
        RS = np.zeros((len(reps), len(orb)), dtype=np.int64)
        for i, a in enumerate(reps):
            ids = lab[a * M: (a + 1) * M]
            for o in ids:
                RS[i, orb[int(o)]] += 1
        return RS
    S["rowsum"] = {"main": rowsum_matrix(S["lab3"], S["mono_orb3"], S["orb3"], M3),
                   **{typ: rowsum_matrix(S["mult"][typ]["lab"], S["mult"][typ]["mono_orb"], S["mult"][typ]["orb"], M2)
                      for typ in PAIR_REPS}}
    log("build done")
    return S
