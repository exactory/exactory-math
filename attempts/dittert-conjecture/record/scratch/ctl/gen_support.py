"""Generate a kernel-checkable Lean certificate for one support polynomial `NearZero.support n z`
on a closed interval [left, right], against the blueprint definitions in Dittert.Scalar.Defs8.

Power-basis construction in exact rationals; every intermediate polynomial gets explicit
coefficients so that each Lean lemma is a small `ring` identity. Imports no checker code.
Usage: python3 gen_support.py N Z LEFT RIGHT OUT.lean META.json   (LEFT, RIGHT as fractions)
"""
from fractions import Fraction as Q
from math import comb, factorial
import json, sys


def add(*terms):
    out = [Q(0)] * max(map(len, terms))
    for term in terms:
        for i, v in enumerate(term):
            out[i] += v
    return out


def scale(t, c):
    return [c * x for x in t]


def mul(a, b):
    out = [Q(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x == 0:
            continue
        for j, y in enumerate(b):
            out[i + j] += x * y
    return out


def power(a, k):
    out = [Q(1)]
    for _ in range(k):
        out = mul(out, a)
    return out


def trim(p):
    p = list(p)
    while len(p) > 1 and p[-1] == 0:
        p.pop()
    return p


def gamma(k):
    return Q(factorial(k), k ** k)


def rat(q):
    q = Q(q)
    if q.denominator == 1:
        return f"({q.numerator} : ℝ)"
    return f"({q.numerator} / {q.denominator} : ℝ)"


def poly(name, coeffs):
    terms = " + ".join(f"{rat(c)} * x^{k}" for k, c in enumerate(coeffs))
    return f"def {name} (x : ℝ) : ℝ := {terms}"


def generate(n, z, left, right):
    m = n - 1 - z
    g = gamma(n)
    kappa = Q(factorial(n - 2) * (n - 2) ** (n - 2), (n - 1) ** (2 * n - 4))
    L = kappa * (1 + Q(1, 2 * n * n))
    rect = gamma(n - z) * gamma(n - 1) / gamma(n - 1 - z)
    floor = max(L, rect) if n == 8 else L
    floor_is_rect = (n == 8 and rect >= L)
    width = right - left
    u = [left, width]
    one = [Q(1)]
    E = trim(add(one, scale(u, -(2 - g))))
    H = trim(scale(u, 1 - g))
    T = trim(add(E, scale(H, -Q(1, n - 1))))
    Qp = trim(add(scale(power(E, n - 1), 2 - g), scale(power(T, n - 1), -1)))
    V = trim(add(one, scale(u, -1)))
    W = trim(add(mul(add([Q(n - 1)], u), Qp), scale(power(E, n - 1), -m)))
    S = trim(add(mul(add([2 - g], scale(power(V, n), floor)), power(E, n)),
                 scale(mul(add(E, H), power(T, n - 1)), -1)))
    Qpow = trim(power(Qp, n - 1))
    P = trim(mul(Qpow, S))
    Epow = trim(power(E, n + (n - 1) * m))
    Wpow = trim(power(W, z))
    R = trim(mul(mul(V, Epow), Wpow))
    G = trim(add(scale(P, Q(z ** z)), scale(R, -1)))
    N = len(G) - 1
    assert N == n * n + 1, (N, n)
    b = [sum((G[i] * comb(N - i, k - i) for i in range(k + 1)), Q(0)) for k in range(N + 1)]
    assert min(b) > 0, ("Bernstein coefficient not positive", min(b))
    CH = 8
    chunks = [list(range(j, min(j + CH, N + 1))) for j in range(0, N + 1, CH)]

    def bern_chunk(ks):
        return " +\n    ".join(f"{rat(b[k])} * x^{k} * (1-x)^{N-k}" for k in ks)

    def power_of_chunk(ks):
        acc = [Q(0)] * (N + 1)
        for k in ks:
            pw = power([Q(1), Q(-1)], N - k)
            for i, c in enumerate(pw):
                acc[k + i] += b[k] * c
        return acc

    ns = f"Support{n}z{z}"
    chunk_defs = "\n".join(f"def C{j} (x : ℝ) : ℝ :=\n    {bern_chunk(ks)}" for j, ks in enumerate(chunks))
    chunk_polys = "\n".join(poly(f"D{j}", trim(power_of_chunk(ks))) for j, ks in enumerate(chunks))
    chunk_lemmas = "\n".join(f"theorem hC{j} (x : ℝ) : C{j} x = D{j} x := by\n  unfold C{j} D{j}; ring"
                             for j in range(len(chunks)))
    cert_sum = " + ".join(f"C{j} x" for j in range(len(chunks)))
    rw_list = ", ".join(f"hC{j}" for j in range(len(chunks)))
    unfold_C = " ".join(f"C{j}" for j in range(len(chunks)))
    unfold_D = " ".join(f"D{j}" for j in range(len(chunks)))
    if n == 8:
        floor_proof = (f"  unfold NearZero.supportFloor; simp only [if_true]\n"
                       f"  rw [{'max_eq_right' if floor_is_rect else 'max_eq_left'} (by norm_num [NearZero.lower, NearZero.kappa, NearZero.gamma, Nat.factorial])]\n"
                       f"  norm_num [NearZero.lower, NearZero.kappa, NearZero.gamma, Nat.factorial]")
    else:
        floor_proof = (f"  unfold NearZero.supportFloor; simp only [show ({n} : ℕ) ≠ 8 by decide, if_false]\n"
                       f"  norm_num [NearZero.lower, NearZero.kappa, NearZero.gamma, Nat.factorial]")
    lean = f'''import Dittert.Scalar.Defs8
import Mathlib.Tactic.NormNum
import Mathlib.Tactic.Ring
import Mathlib.Tactic.Positivity
import Mathlib.Tactic.Linarith
import Mathlib.Tactic.LinearCombination

/-!
# Kernel certificate: `NearZero.support {n} {z}` is positive on `[{left}, {right}]`

Generated by scratch/ctl/gen_support.py (independent power-basis construction). Every
coefficient below is an explicit rational; Lean establishes the identities and the positivity.
Parametrisation `u = {left} + ({width}) x`, `x ∈ [0,1]`; the Bernstein coefficients of the
degree-{N} polynomial are all positive, so no subdivision is needed.
-/

set_option maxHeartbeats 40000000

noncomputable section
namespace {ns}

/-- The affine parametrisation of the interval. -/
def uu (x : ℝ) : ℝ := {rat(left)} + {rat(width)} * x

{poly("E", E)}
{poly("H", H)}
{poly("T", T)}
{poly("Qp", Qp)}
{poly("V", V)}
{poly("W", W)}
{poly("S", S)}
{poly("Qpow", Qpow)}
{poly("P", P)}
{poly("Epow", Epow)}
{poly("Wpow", Wpow)}
{poly("R", R)}

theorem gamma_val : NearZero.gamma {n} = {rat(g)} := by
  unfold NearZero.gamma; norm_num [Nat.factorial]
theorem floor_val : NearZero.supportFloor {n} {z} = {rat(floor)} := by
{floor_proof}

theorem hE (x : ℝ) : NearZero.e {n} (uu x) = E x := by
  unfold NearZero.e uu E; rw [gamma_val]; ring
theorem hH (x : ℝ) : NearZero.h {n} (uu x) = H x := by
  unfold NearZero.h uu H; rw [gamma_val]; ring
theorem hT (x : ℝ) : NearZero.t {n} (uu x) = T x := by
  unfold NearZero.t T; rw [hE, hH]; unfold E H; norm_num; ring
theorem hQ (x : ℝ) : NearZero.q {n} (uu x) = Qp x := by
  unfold NearZero.q; rw [hE, hT, gamma_val]; unfold E T Qp; norm_num; ring
theorem hV (x : ℝ) : 1 - uu x = V x := by
  unfold uu V; ring
theorem hW (x : ℝ) : NearZero.w {n} {z} (uu x) = W x := by
  unfold NearZero.w; rw [hQ, hE]; unfold uu Qp E W; norm_num; ring
theorem hS (x : ℝ) : NearZero.s {n} {z} (uu x) = S x := by
  unfold NearZero.s; rw [hE, hH, hT, hV, gamma_val, floor_val]; unfold E H T V S; norm_num; ring
theorem hQpow (x : ℝ) : (Qp x)^{n - 1} = Qpow x := by
  unfold Qp Qpow; ring
theorem hP (x : ℝ) : Qpow x * S x = P x := by
  unfold Qpow S P; ring
theorem hEpow (x : ℝ) : (E x)^{n + (n - 1) * m} = Epow x := by
  unfold E Epow; ring
theorem hWpow (x : ℝ) : (W x)^{z} = Wpow x := by
  unfold W Wpow; ring
theorem hR (x : ℝ) : V x * Epow x * Wpow x = R x := by
  unfold V Epow Wpow R; ring

{chunk_defs}

{chunk_polys}

{chunk_lemmas}

def certificate (x : ℝ) : ℝ := {cert_sum}

theorem hG (x : ℝ) : ({z ** z} : ℝ) * P x - R x = certificate x := by
  unfold certificate; rw [{rw_list}]; unfold P R {unfold_D}; ring

theorem identity (x : ℝ) : NearZero.support {n} {z} (uu x) = certificate x := by
  unfold NearZero.support
  rw [hQ, hS, hV, hE, hW, hQpow, hEpow, hWpow]
  norm_num
  linear_combination ({z ** z} : ℝ) * hP x - hR x + hG x

theorem positive (x : ℝ) (hx : 0 ≤ x) (hx1 : x ≤ 1) : 0 < certificate x := by
  have hy : 0 ≤ 1 - x := sub_nonneg.mpr hx1
  by_cases hlt : x < 1
  · have hyp : 0 < 1 - x := sub_pos.mpr hlt
    unfold certificate {unfold_C}
    positivity
  · have heq : x = 1 := le_antisymm hx1 (le_of_not_gt hlt)
    subst x
    norm_num [certificate, {unfold_C.replace(" ", ", ")}]

theorem support_certificate (u : ℝ) (hu : {rat(left)} ≤ u) (hu1 : u ≤ {rat(right)}) :
    0 < NearZero.support {n} {z} u := by
  have hx : 0 ≤ (u - {rat(left)}) / {rat(width)} := by
    apply div_nonneg <;> linarith
  have hx1 : (u - {rat(left)}) / {rat(width)} ≤ 1 := by
    rw [div_le_one (by norm_num)]; linarith
  have hp := positive _ hx hx1
  rw [← identity] at hp
  have hid : uu ((u - {rat(left)}) / {rat(width)}) = u := by unfold uu; ring
  rw [hid] at hp
  exact hp

end {ns}
'''
    meta = {"n": n, "z": z, "m": m, "interval": [str(left), str(right)], "degree": N, "floor": str(floor),
            "floor_is_rectangle": floor_is_rect, "positive_coefficients": len(b),
            "smallest": str(min(b)), "largest": str(max(b)), "coefficients": [str(c) for c in b]}
    return lean, meta


if __name__ == "__main__":
    n, z = int(sys.argv[1]), int(sys.argv[2])
    left, right = Q(sys.argv[3]), Q(sys.argv[4])
    lean, meta = generate(n, z, left, right)
    open(sys.argv[5], "w").write(lean)
    open(sys.argv[6], "w").write(json.dumps(meta, indent=1) + "\n")
    print("n", n, "z", z, "degree", meta["degree"], "min coeff", float(Q(meta["smallest"])),
          "max digits", max(len(str(Q(c).numerator)) for c in meta["coefficients"]))
